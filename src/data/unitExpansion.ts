function cloneQuestions(qs: LessonQuestion[]): LessonQuestion[] {
  return JSON.parse(JSON.stringify(qs)) as LessonQuestion[];
}

export function expandUnitsToEightNodes(baseUnits: Unit[]): Unit[] {
  return baseUnits.map((unit) => {
    const pack = UNIT_EXPANSION_PACKS[unit.id];
    const fillBlanks = UNIT_FILL_BLANK_QUESTIONS[unit.id];
    const [base1, base2, base3] = unit.lessons;
    const allBaseQuestions = unit.lessons.flatMap((l) => l.questions);

    const listenFromBase = allBaseQuestions.filter((q) => q.type === 'listen');
    const pairsFromBase = allBaseQuestions.filter((q) => q.type === 'pairs');
    const wordbankFromBase = allBaseQuestions.filter((q) => q.type === 'wordbank');
    const mcqFromBase = allBaseQuestions.filter((q) => q.type === 'mcq');

    // Node 2 (Lesson 2): Guided Practice + Fill-in-the-Blank
    const node2Questions: LessonQuestion[] = fillBlanks?.[0]
      ? [...base2.questions, fillBlanks[0]]
      : base2.questions;

    // Node 5 (Lesson 4): Everyday Dialogue opening with Fill-in-the-Blank
    const dialogueNodeQuestions: LessonQuestion[] = fillBlanks?.[1]
      ? [fillBlanks[1], ...(pack?.dialogueQuestions ?? base3.questions)]
      : (pack?.dialogueQuestions ?? base3.questions);

    // Node 6 (Lesson 5): Audio & Listening Challenge + Fill-in-the-Blank
    const listeningQuestions: LessonQuestion[] = [];
    if (pack?.extraListeningQuestions[0]) listeningQuestions.push(pack.extraListeningQuestions[0]);
    if (fillBlanks?.[2]) listeningQuestions.push(fillBlanks[2]);
    if (listenFromBase[0]) listeningQuestions.push(listenFromBase[0]);
    if (pack?.extraListeningQuestions[1]) listeningQuestions.push(pack.extraListeningQuestions[1]);
    if (pack?.guidebook && pack.guidebook.length >= 4) {
      listeningQuestions.push({
        type: 'pairs',
        prompt: 'കേട്ട് അതിവേഗം ജോഡികൾ യോജിപ്പിക്കുക',
        pairs: pack.guidebook.slice(0, 4).map((g) => ({ ar: g.ar.split(' / ')[0], tr: g.tr.split(' / ')[0], ml: g.ml.split(' / ')[0] })),
      });
    } else if (pairsFromBase[0]) {
      listeningQuestions.push(pairsFromBase[0]);
    }

    // Node 7: Hard Practice (opens with Fill-in-the-Blank + challenging mix)
    const hardQuestions: LessonQuestion[] = [];
    if (fillBlanks?.[3]) hardQuestions.push(fillBlanks[3]);
    if (pack?.hardExtraQuestions[0]) hardQuestions.push(pack.hardExtraQuestions[0]);
    if (wordbankFromBase[0]) hardQuestions.push(wordbankFromBase[0]);
    if (pack?.dialogueQuestions[3]) hardQuestions.push(pack.dialogueQuestions[3]);
    if (mcqFromBase[mcqFromBase.length - 1]) hardQuestions.push(mcqFromBase[mcqFromBase.length - 1]);
    if (listenFromBase[listenFromBase.length - 1]) hardQuestions.push(listenFromBase[listenFromBase.length - 1]);

    // Node 8: Unit Review / Trophy (comprehensive mastery challenge unlocking next unit)
    const trophyQuestions: LessonQuestion[] = [];
    if (mcqFromBase[0]) trophyQuestions.push(mcqFromBase[0]);
    if (pairsFromBase[pairsFromBase.length - 1]) trophyQuestions.push(pairsFromBase[pairsFromBase.length - 1]);
    if (pack?.dialogueQuestions[1]) trophyQuestions.push(pack.dialogueQuestions[1]);
    if (wordbankFromBase[wordbankFromBase.length - 1]) trophyQuestions.push(wordbankFromBase[wordbankFromBase.length - 1]);
    if (pack?.dialogueQuestions[0]) trophyQuestions.push(pack.dialogueQuestions[0]);

    const eightNodes: Lesson[] = [
      {
        id: `${unit.id}_n1`,
        title: base1.title,
        subtitle: 'അടിസ്ഥാന പദാവലി',
        icon: '⭐',
        nodeType: 'lesson',
        xpReward: 15,
        questions: cloneQuestions(base1.questions),
      },
      {
        id: `${unit.id}_n2`,
        title: base2.title,
        subtitle: 'ഉച്ചാരണവും പരിശീലനവും',
        icon: '📖',
        nodeType: 'practice',
        xpReward: 15,
        questions: cloneQuestions(node2Questions),
      },
      {
        id: `${unit.id}_n3`,
        title: base3.title,
        subtitle: 'വാക്യ നിർമ്മാണം',
        icon: '🧩',
        nodeType: 'wordbank',
        xpReward: 15,
        questions: cloneQuestions(base3.questions),
      },
      {
        id: `${unit.id}_n4`,
        title: 'നിധിപ്പെട്ടി · ബോണസ്',
        subtitle: '+25 XP · +1 ❤️',
        icon: '🎁',
        nodeType: 'chest',
        xpReward: TREASURE_CHEST_XP,
        heartReward: TREASURE_CHEST_HEARTS,
        questions: [],
      },
      {
        id: `${unit.id}_n5`,
        title: pack?.dialogueTitle ?? 'നിത്യോപയോഗ സംഭാഷണം',
        subtitle: 'ദൈനംദിന പ്രയോഗം',
        icon: '💬',
        nodeType: 'dialogue',
        xpReward: 15,
        questions: cloneQuestions(dialogueNodeQuestions),
      },
      {
        id: `${unit.id}_n6`,
        title: pack?.listeningTitle ?? 'ശ്രവണ വെല്ലുവിളി',
        subtitle: 'കേട്ട് മനസ്സിലാക്കാം',
        icon: '🎧',
        nodeType: 'listening',
        xpReward: 20,
        questions: cloneQuestions(listeningQuestions),
      },
      {
        id: `${unit.id}_n7`,
        title: pack?.hardTitle ?? 'കഠിന പരിശീലനം',
        subtitle: 'മിക്സഡ് വെല്ലുവിളി',
        icon: '⚡',
        nodeType: 'hard',
        xpReward: 20,
        questions: cloneQuestions(hardQuestions),
      },
      {
        id: `${unit.id}_n8`,
        title: pack?.trophyTitle ?? `യൂണിറ്റ് ${unit.number} ട്രോഫി പരീക്ഷ`,
        subtitle: 'അടുത്ത യൂണിറ്റ് അൺലോക്ക്',
        icon: '🏆',
        nodeType: 'trophy',
        xpReward: 25,
        questions: cloneQuestions(trophyQuestions),
      },
    ];

    return {
      ...unit,
      guidebookTip: pack?.guidebookTip,
      guidebook: pack?.guidebook,
      mascot: pack?.mascot,
      lessons: eightNodes,
    };
  });
}
