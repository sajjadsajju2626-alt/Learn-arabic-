function buildScenario(spec: RawScenarioSpec): VideoCallScenario {
  const isTariq = spec.characterKey === 'tariq';
  return {
    id: `${spec.unitId}_vc_scenario`,
    unitNumber: spec.unitNumber,
    characterKey: spec.characterKey,
    characterNameEn: isTariq ? 'Tariq' : 'Layla',
    characterNameMl: isTariq ? 'താരിഖ്' : 'ലൈല',
    characterNameAr: isTariq ? 'طَارِق' : 'لَيْلَى',
    characterAvatar: isTariq ? '👳‍♂️' : '🧕',
    sceneTitleMl: spec.sceneTitleMl,
    sceneSettingMl: spec.sceneSettingMl,
    backdropImage: isTariq ? TARIQ_BACKDROP : LAYLA_BACKDROP,
    turns: spec.turns,
  };
}

