/**
 * Cleanly combines accumulated speech segments across pauses and recognition restarts
 * without dropping words or duplicating whitespace.
 */
export function mergeSpeechTranscripts(
  committed: string,
  sessionFinal: string,
  sessionInterim: string
): string {
  const parts = [committed, sessionFinal, sessionInterim]
    .map((p) => String(p ?? '').trim())
    .filter(Boolean);
  return parts.join(' ').replace(/\s+/g, ' ').trim();
}

/**
 * Strips any guillemet quote echoing («...») so Tariq never parrots raw user text.
 */
export function stripQuotedEcho(text: string): string {
  return String(text ?? '')
    .replace(/[«»]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Detects the primary conversational intent from any spoken Arabic sentence.
 */
export function detectArabicIntent(userSpokenText: string): {
  intent: VideoCallIntent;
  matchedKeyword: string | null;
} {
  const norm = normalizeArabicSpeech(userSpokenText);
  if (!norm) {
    return { intent: 'general_open', matchedKeyword: null };
  }
  const rawTokens = norm.split(/\s+/).filter(Boolean);
  const tokenSet = new Set<string>();
  for (const tok of rawTokens) {
    tokenSet.add(tok);
    if (tok.startsWith('ال') && tok.length > 3) tokenSet.add(tok.slice(2));
    if (tok.startsWith('وال') && tok.length > 4) tokenSet.add(tok.slice(3));
    if (tok.startsWith('بال') && tok.length > 4) tokenSet.add(tok.slice(3));
    if (tok.startsWith('لل') && tok.length > 3) tokenSet.add(tok.slice(2));
    if (tok.startsWith('و') && tok.length > 3) tokenSet.add(tok.slice(1));
  }

  for (const rule of INTENT_RULES) {
    for (const kw of rule.keywords) {
      if (kw.includes(' ')) {
        if (norm.includes(kw)) {
          return { intent: rule.intent, matchedKeyword: kw };
        }
      } else if (tokenSet.has(kw)) {
        return { intent: rule.intent, matchedKeyword: kw };
      }
    }
  }

  for (const rule of INTENT_RULES) {
    if (rule.intent === 'negative' || rule.intent === 'affirmative' || rule.intent === 'greeting') {
      continue;
    }
    for (const kw of rule.keywords) {
      if (kw.length < 3 || kw.includes(' ')) continue;
      for (const tok of tokenSet) {
        if (tok.includes(kw)) {
          return { intent: rule.intent, matchedKeyword: kw };
        }
      }
    }
  }

  return { intent: 'general_open', matchedKeyword: null };
}

