function pickNonRepeatingVariant(
  variants: IntentVariant[],
  history: VideoCallChatEntry[],
  turnIndex: number
): IntentVariant {
  if (variants.length <= 1) return variants[0];
  const prevCharTexts = new Set(
    history.filter((h) => h.speaker === 'character').map((h) => normalizeArabicSpeech(h.text))
  );
  for (let offset = 0; offset < variants.length; offset++) {
    const candidate = variants[(turnIndex + offset) % variants.length];
    const followUpNorm = normalizeArabicSpeech(candidate.followUpAr);
    let alreadyAsked = false;
    for (const prev of prevCharTexts) {
      if (followUpNorm && prev.includes(followUpNorm)) {
        alreadyAsked = true;
        break;
      }
    }
    if (!alreadyAsked) return candidate;
  }
  return variants[turnIndex % variants.length];
}

/**
 * Smart Intent-Based Local Arabic Conversational Engine (100% offline-capable for GitHub Pages / APK).
 * Understands the meaning of whatever the user spoke — NEVER parrots or quotes raw words («...») —
 * and replies naturally in vocalized Arabic with full Harakat plus a directly related follow-up question.
 */
export function generateSmartArabicReply(req: DynamicVideoCallRequest): DynamicVideoCallResponse {
  const { userSpokenText, scenario, turnIndex, history } = req;
  const totalTurns = scenario.turns.length;
  const isFinalTurn = turnIndex + 1 >= totalTurns;

  const spokenWords = Math.max(1, countSpokenArabicWords(userSpokenText));
  const xpEarned = Math.min(16, Math.max(2, spokenWords * 2));
  const norm = normalizeArabicSpeech(userSpokenText);
  const { intent } = detectArabicIntent(userSpokenText);

  const allVariants = buildIntentVariants();
  const variants = allVariants[intent] || allVariants.general_open;
  const chosen = pickNonRepeatingVariant(variants, history || [], turnIndex);

  let ackAr = chosen.ackAr;
  let ackTr = chosen.ackTr;
  let ackMl = chosen.ackMl;

  if (intent === 'food_drink') {
    const sub = getSubTopicFoodAck(norm);
    if (sub) {
      ackAr = sub.ar;
      ackTr = sub.tr;
      ackMl = sub.ml;
    }
  } else if (intent === 'travel') {
    const sub = getSubTopicTravelAck(norm);
    if (sub) {
      ackAr = sub.ar;
      ackTr = sub.tr;
      ackMl = sub.ml;
    }
  }

  if (isFinalTurn) {
    return {
      replyArabic: stripQuotedEcho(
        `${ackAr} شُكْرًا جَزِيلًا عَلَى هٰذِهِ الْمُكَالَمَةِ الرَّائِعَةِ يَا صَدِيقِي! إِلَى اللِّقَاءِ قَرِيبًا!`
      ),
      replyTransliteration: `${ackTr} ശുക്റൻ ജസീലൻ അലാ ഹാദിഹിൽ മുകാലമത്തിർറാഇഅത്തി യാ സ്വദീഖീ! ഇലല്ലിഖാഇ ഖരീബൻ!`,
      replyMalayalam: `${ackMl} ഈ മനോഹരമായ വീഡിയോ കോളിന് വളരെ നന്ദി സുഹൃത്തേ! ഉടൻ വീണ്ടും കാണാം!`,
      nextHints: [],
      xpEarned,
      isFinalTurn: true,
      intent,
      source: 'smart_local',
    };
  }

  return {
    replyArabic: stripQuotedEcho(`${ackAr} ${chosen.followUpAr}`),
    replyTransliteration: `${ackTr} ${chosen.followUpTr}`,
    replyMalayalam: `${ackMl} ${chosen.followUpMl}`,
    nextHints: chosen.hints,
    xpEarned,
    isFinalTurn: false,
    intent,
    source: 'smart_local',
  };
}

/**
 * Checks whether the runtime host can reach the server-side Gemini endpoint
 * (automatically skips static hosts like GitHub Pages or Android WebView file/capacitor origins).
 */
export function canUseServerGeminiEndpoint(loc?: { protocol?: string; hostname?: string }): boolean {
  const target =
    loc ?? (typeof window !== 'undefined' ? window.location : { protocol: '', hostname: '' });
  const proto = String(target.protocol || '').toLowerCase();
  const host = String(target.hostname || '').toLowerCase();
  if (proto !== 'http:' && proto !== 'https:') return false;
  if (!host || host.endsWith('.github.io')) return false;
  return true;
}

/**
 * Requests a natural, open-topic vocalized Arabic reply for whatever the learner spoke:
 * - Automatically calls server-side Gemini 2.5 Flash (`/api/video-call-reply`) when available.
 * - Seamlessly falls back to the Smart Intent-Based Arabic Responder on GitHub Pages,
 *   Android APK, or offline sessions without ever echoing/quoting raw user words.
 */
export async function requestDynamicVideoCallReply(
  req: DynamicVideoCallRequest,
  timeoutMs = 7000
): Promise<DynamicVideoCallResponse> {
  if (canUseServerGeminiEndpoint() && typeof fetch === 'function') {
    const controller = typeof AbortController !== 'undefined' ? new AbortController() : null;
    const timer =
      controller && typeof window !== 'undefined'
        ? window.setTimeout(() => controller.abort(), timeoutMs)
        : null;

    try {
      const response = await fetch('/api/video-call-reply', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        signal: controller?.signal,
        body: JSON.stringify({
          userSpokenText: req.userSpokenText,
          characterKey: req.scenario.characterKey,
          characterNameEn: req.scenario.characterNameEn,
          characterNameMl: req.scenario.characterNameMl,
          characterNameAr: req.scenario.characterNameAr,
          sceneTitleMl: req.scenario.sceneTitleMl,
          sceneSettingMl: req.scenario.sceneSettingMl,
          unitNumber: req.scenario.unitNumber,
          turnIndex: req.turnIndex,
          totalTurns: req.scenario.turns.length,
          history: req.history.slice(-10),
        }),
      });

      if (response.ok) {
        const data = (await response.json()) as Partial<DynamicVideoCallResponse>;
        const cleanArabic = stripQuotedEcho(typeof data.replyArabic === 'string' ? data.replyArabic : '');
        if (cleanArabic && /[\u0621-\u064A]/.test(cleanArabic)) {
          const fallback = generateSmartArabicReply(req);
          const validHints =
            Array.isArray(data.nextHints) && data.nextHints.length > 0
              ? data.nextHints
                  .filter(
                    (h): h is VideoCallReplySuggestion =>
                      Boolean(h && typeof h.ar === 'string' && h.ar.trim() && typeof h.ml === 'string')
                  )
                  .map((h) => ({
                    ar: stripQuotedEcho(h.ar),
                    tr: h.tr,
                    ml: h.ml,
                  }))
              : fallback.nextHints;

          return {
            replyArabic: cleanArabic,
            replyTransliteration:
              typeof data.replyTransliteration === 'string' && data.replyTransliteration.trim()
                ? data.replyTransliteration.trim()
                : fallback.replyTransliteration,
            replyMalayalam:
              typeof data.replyMalayalam === 'string' && data.replyMalayalam.trim()
                ? data.replyMalayalam.trim()
                : fallback.replyMalayalam,
            nextHints: fallback.isFinalTurn ? [] : validHints.slice(0, 3),
            xpEarned:
              typeof data.xpEarned === 'number' && data.xpEarned > 0
                ? Math.round(data.xpEarned)
                : fallback.xpEarned,
            isFinalTurn: fallback.isFinalTurn,
            source: 'gemini',
          };
        }
      }
    } catch {
      // Static hosting, offline, or aborted request -> seamlessly fall back to Smart Arabic Responder
    } finally {
      if (timer !== null && typeof window !== 'undefined') {
        window.clearTimeout(timer);
      }
    }
  }

  return generateSmartArabicReply(req);
}
